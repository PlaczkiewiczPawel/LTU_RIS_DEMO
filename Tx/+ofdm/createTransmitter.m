function tx = createTransmitter(cfg)
%CREATETRANSMITTER Construct a configured USRP transmitter System object.

    rateFactor = cfg.radio.masterClockRate / cfg.radio.samplingFrequency;
    tx = comm.SDRuTransmitter( ...
        'Platform', cfg.radio.platform, ...
        'IPAddress', cfg.radio.txIPAddress, ...
        'CenterFrequency', cfg.radio.centerFrequency, ...
        'InterpolationFactor', rateFactor, ...
        'Gain', cfg.radio.txGain, ...
        'ClockSource', cfg.radio.clockSource);
    tx.EnableBurstMode = false;
end

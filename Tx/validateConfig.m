function validateConfig(cfg)
%VALIDATECONFIG Fail early when OFDM or radio assumptions are inconsistent.

    arguments
        cfg (1,1) struct
    end

    requiredGroups = ["radio", "ofdm", "receiver", "visualization", ...
                      "transmitter", "simulation"];
    for group = requiredGroups
        assert(isfield(cfg, group), 'OFDM:MissingConfiguration', ...
            'Configuration group "%s" is missing.', group);
    end

    p = cfg.ofdm;
    assert(p.fftLength > 0 && mod(p.fftLength, 2) == 0, ...
        'OFDM:InvalidFFTLength', 'fftLength must be a positive even integer.');
    assert(p.numUsedSubcarriers > 0 && mod(p.numUsedSubcarriers, 2) == 0, ...
        'OFDM:InvalidUsedSubcarriers', ...
        'numUsedSubcarriers must be a positive even integer.');
    assert(p.numUsedSubcarriers < p.fftLength, ...
        'OFDM:TooManySubcarriers', 'Occupied subcarriers must leave room for DC.');
    assert(p.cyclicPrefixLength > 0 && p.cyclicPrefixLength < p.fftLength, ...
        'OFDM:InvalidCyclicPrefix', ...
        'cyclicPrefixLength must be between zero and fftLength.');
    assert(p.numSymbols >= 1 && p.numSymbols == fix(p.numSymbols), ...
        'OFDM:InvalidSymbolCount', 'numSymbols must be a positive integer.');
    assert(p.numFrames >= 1 && p.numFrames == fix(p.numFrames), ...
        'OFDM:InvalidFrameCount', 'numFrames must be a positive integer.');

    roles = {p.pilotPositions, p.framePositions, p.symbolPositions};
    allPositions = [roles{:}];
    assert(all(allPositions >= 1 & allPositions <= p.numUsedSubcarriers), ...
        'OFDM:PositionOutOfRange', ...
        'Pilot and metadata positions must address occupied subcarriers.');
    assert(numel(unique(allPositions)) == numel(allPositions), ...
        'OFDM:OverlappingPositions', ...
        'Pilot, frame, and symbol positions must be disjoint.');
    assert(p.numFrames <= 4^numel(p.framePositions), ...
        'OFDM:FrameNumberOverflow', ...
        'framePositions cannot represent all configured frame numbers.');
    assert(p.numSymbols <= 4^numel(p.symbolPositions), ...
        'OFDM:SymbolNumberOverflow', ...
        'symbolPositions cannot represent all configured symbol numbers.');
    assert(isfinite(p.pilotSymbol) && p.pilotSymbol ~= 0, ...
        'OFDM:InvalidPilot', 'pilotSymbol must be finite and nonzero.');

    assert(isscalar(cfg.receiver.minimumTimingMetric) && ...
           isfinite(cfg.receiver.minimumTimingMetric) && ...
           cfg.receiver.minimumTimingMetric >= 0 && cfg.receiver.minimumTimingMetric <= 1, ...
        'OFDM:InvalidTimingThreshold', 'minimumTimingMetric must be in [0,1].');
    assert(any(strcmp(cfg.radio.clockSource, {'External', 'Internal'})), ...
        'OFDM:InvalidClockSource', 'clockSource must be External or Internal.');

    interpolation = cfg.radio.masterClockRate / cfg.radio.samplingFrequency;
    assert(interpolation >= 1 && interpolation == fix(interpolation), ...
        'OFDM:InvalidRateFactor', ...
        'masterClockRate/samplingFrequency must be a positive integer.');
    assert(cfg.radio.samplesPerRead >= 1 && ...
           cfg.radio.samplesPerRead == fix(cfg.radio.samplesPerRead), ...
        'OFDM:InvalidReadLength', 'samplesPerRead must be a positive integer.');
    assert(cfg.receiver.integerOffsetRange >= 0 && ...
           cfg.receiver.integerOffsetRange == fix(cfg.receiver.integerOffsetRange), ...
        'OFDM:InvalidOffsetRange', ...
        'integerOffsetRange must be a nonnegative integer.');
    assert(cfg.transmitter.amplitudeScale > 0 && ...
           cfg.transmitter.amplitudeScale <= 1, ...
        'OFDM:InvalidAmplitudeScale', ...
        'amplitudeScale must be in the interval (0, 1].');
end
